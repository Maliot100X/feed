/**
 * Prompt Logger
 *
 * Logs LLM prompts and responses to markdown files for monitoring and analysis.
 * Files are saved to: debug/prompts/<timestamp>_<promptType>.md
 *
 * Enable via environment variables:
 * - DEBUG_SAVE_PROMPTS=true
 * - DEBUG_PROMPTS=true
 */

import { randomUUID } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import * as path from 'node:path';
import { logger } from '@feed/shared';

export interface PromptLogEntry {
  promptType: string;
  promptTemplate?: string;
  input: string;
  output: string;
  parsedOutput?: string;
  metadata?: {
    provider?: string;
    model?: string;
    temperature?: number;
    maxTokens?: number;
    format?: string;
  };
}

/**
 * Check if prompt logging is enabled via environment variable
 */
export function isPromptLoggingEnabled(): boolean {
  return (
    process.env.DEBUG_SAVE_PROMPTS === 'true' ||
    process.env.DEBUG_SAVE_PROMPTS === '1' ||
    process.env.DEBUG_PROMPTS === 'true' ||
    process.env.DEBUG_PROMPTS === '1'
  );
}

/**
 * Log a prompt and its response to a markdown file.
 *
 * Debug logging is non-authoritative: filesystem failures are logged and
 * never propagate into the LLM call that produced the entry.
 */
export async function logPrompt(entry: PromptLogEntry): Promise<void> {
  if (!isPromptLoggingEnabled()) {
    return;
  }

  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const safePromptType = entry.promptType.replace(/[^a-zA-Z0-9-_]/g, '_');
  // Random suffix prevents same-millisecond logs of one type overwriting each other.
  const filename = `${timestamp}_${safePromptType}_${randomUUID().slice(0, 8)}.md`;
  const debugDir = path.join(process.cwd(), 'debug', 'prompts');
  const filepath = path.join(debugDir, filename);

  // Build markdown content
  const lines = [
    `# Prompt Debug Log: ${entry.promptType}`,
    ``,
    `**Timestamp:** ${new Date().toISOString()}`,
    ``,
  ];

  // Add metadata if present
  if (entry.metadata) {
    lines.push(`## Metadata`, ``);
    if (entry.metadata.provider)
      lines.push(`- **Provider:** ${entry.metadata.provider}`);
    if (entry.metadata.model)
      lines.push(`- **Model:** ${entry.metadata.model}`);
    if (entry.metadata.temperature !== undefined)
      lines.push(`- **Temperature:** ${entry.metadata.temperature}`);
    if (entry.metadata.maxTokens)
      lines.push(`- **Max Tokens:** ${entry.metadata.maxTokens}`);
    if (entry.metadata.format)
      lines.push(`- **Format:** ${entry.metadata.format}`);
    lines.push(``);
  }

  // Include prompt template in log if provided
  if (entry.promptTemplate) {
    lines.push(`## Prompt Template`, ``);
    lines.push('```');
    lines.push(entry.promptTemplate);
    lines.push('```');
    lines.push(``);
  }

  // Add rendered input
  lines.push(`# Input`, ``);
  lines.push('```');
  lines.push(entry.input);
  lines.push('```');
  lines.push(``);

  // Add raw output
  lines.push(`# Output`, ``);
  lines.push('```');
  lines.push(entry.output);
  lines.push('```');
  lines.push(``);

  // Add parsed output if available
  if (entry.parsedOutput) {
    lines.push(`## Parsed Output`, ``);
    lines.push('```json');
    lines.push(entry.parsedOutput);
    lines.push('```');
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`Generated by Feed Prompt Logger`);
  lines.push(``);

  try {
    await mkdir(debugDir, { recursive: true });
    await writeFile(filepath, lines.join('\n'), {
      encoding: 'utf-8',
      flag: 'wx',
    });
  } catch (error) {
    logger.warn(
      'Failed to write prompt debug log',
      {
        error: error instanceof Error ? error.message : String(error),
        promptType: entry.promptType,
      },
      'PromptLogger'
    );
    return;
  }

  logger.debug(
    `Logged prompt to ${filename}`,
    {
      promptType: entry.promptType,
      filepath,
    },
    'PromptLogger'
  );
}
